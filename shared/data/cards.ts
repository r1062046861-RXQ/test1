export interface CardTemplateCount {
  templateId: string;
  card: Card;
  count: number;
  instances: Card[];
}

export const getTemplateCardId = (card: Card) => {
  if (card._templateId && CARD_LIBRARY[card._templateId]) return card._templateId;
  if (CARD_LIBRARY[card.id]) return card.id;
  return Object.entries(CARD_LIBRARY).find(([, template]) => template.name === card.name)?.[0] ?? null;
};

export const countCardCopies = (cards: Card[], templateId: string) =>
  cards.reduce((total, card) => total + (getTemplateCardId(card) === templateId ? 1 : 0), 0);

export const countCardsByTemplate = (cards: Card[]) =>
  cards.reduce<Record<string, CardTemplateCount>>((counts, card) => {
    const templateId = getTemplateCardId(card);
    if (!templateId) return counts;
    if (!counts[templateId]) {
      counts[templateId] = {
        templateId,
        card: CARD_LIBRARY[templateId],
        count: 0,
        instances: [],
      };
    }
    counts[templateId].count += 1;
    counts[templateId].instances.push(card);
    return counts;
  }, {});
