export const getCardCategory = (card: Card): CardCategory => {
  if (card.category) return card.category;
  if (card.effectId === 'status_enemy') return 'enemy';
  return 'herb';
};

export const isHerbCard = (card: Card) => getCardCategory(card) === 'herb';
export const isFormulaCard = (card: Card) => getCardCategory(card) === 'formula';
export const isEquipmentCard = (card: Card) => getCardCategory(card) === 'equipment';
export const isEnemyMechanismCard = (card: Card) => getCardCategory(card) === 'enemy';

